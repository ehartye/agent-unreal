// node --test examples/unreal/unity_build/unity-build.test.mjs  (no Unreal, no dependencies)
// The logs below have the shape Unreal Build Tool wrote on Unreal 5.8.2. Each test changes one fact and expects the matching check to
// fail, so the judge cannot pass by accident.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { evaluate, evaluateReadOnly, summarize, compilerDiagnostics, unityIncludes, compiledUnits, adaptiveExcluded, chunks, MODULE_FILES } from './unity-build-checks.mjs';

const SRC = 'C:\\Temp\\unity-build-x\\Source\\UnityProbe';
const I = 'C:/Temp/unity-build-x/Intermediate/Build/Win64/x64/UnrealEditor/Development/UnityProbe';
const unityText = (...names) => `// This file is automatically generated at compile-time to include some subset of the user-created cpp files.\n${names.map((n) => `#include "${I}/${n}"`).join('\n')}\n`;
const ALL = unityText('PerModuleInline.gen.cpp', 'ProbeAlpha.cpp', 'ProbeBeta.cpp', 'UnityProbeModule.cpp');
const GEN = unityText('PerModuleInline.gen.cpp');
const compileLines = (...names) => names.map((n, i) => `[${i + 1}/${names.length + 3}] Compile [x64] ${n}`).join('\n');
const clashLog = `[1/4] Compile [x64] Module.UnityProbe.cpp
${SRC}\\ProbeBeta.cpp(5,18): error C2374: '\`anonymous-namespace'::BurstCount': redefinition; multiple initialization
${SRC}\\ProbeAlpha.cpp(6,18): note: see declaration of '\`anonymous-namespace'::BurstCount'
${SRC}\\ProbeBeta.cpp(5,18): error C2086: 'const int32 \`anonymous-namespace'::BurstCount': redefinition
${SRC}\\ProbeBeta.cpp(13,14): error C4459: declaration of 'MaxCount' hides global declaration
${SRC}\\ProbeBeta.cpp(14,8): error C2872: 'EState': ambiguous symbol
Result: Failed (OtherCompilationError)`;
const excluded = (...names) => `[Adaptive Build] Excluded from UnityProbe unity file: ${names.join(', ')}`;
const skipped = { ran: false, reason: 'build failed (exit 6)' };
const ok = { ran: true };

const good = () => ({
  small: { exit: 0, log: compileLines('PerModuleInline.gen.cpp', 'ProbeAlpha.cpp', 'ProbeBeta.cpp', 'UnityProbeModule.cpp'), unity: {}, dllChanged: true, followOn: ok },
  adaptive: { exit: 0, log: `${excluded('ProbeAlpha.cpp', 'ProbeBeta.cpp', 'UnityProbeModule.cpp')}\n${compileLines('Module.UnityProbe.cpp')}`, unity: { 'Module.UnityProbe.cpp': GEN }, dllChanged: true, followOn: ok },
  clash: { exit: 6, log: clashLog, unity: { 'Module.UnityProbe.cpp': ALL }, dllChanged: false, followOn: skipped },
  off: { exit: 0, log: 'Target is up to date', unity: { 'Module.UnityProbe.cpp': GEN }, dllChanged: true, followOn: ok },
  fixed: { exit: 0, log: compileLines('Module.UnityProbe.cpp'), unity: { 'Module.UnityProbe.cpp': ALL }, dllChanged: true, followOn: ok },
  chunks: { exit: 0, log: compileLines('Module.UnityProbe.1.cpp'), unity: { 'Module.UnityProbe.1.cpp': GEN, 'Module.UnityProbe.2.cpp': unityText('ProbeAlpha.cpp'), 'Module.UnityProbe.3.cpp': unityText('ProbeBeta.cpp'), 'Module.UnityProbe.4.cpp': unityText('UnityProbeModule.cpp') }, dllChanged: true, followOn: ok },
  gitClean: { exit: 6, log: clashLog, unity: { 'Module.UnityProbe.cpp': ALL }, dllChanged: false, followOn: skipped },
  gitDirty: { exit: 0, log: `Invalidating makefile for UnityProbeProjectEditor (working set of source files changed)\n${excluded('ProbeBeta.cpp')}`, unity: { 'Module.UnityProbe.cpp': unityText('PerModuleInline.gen.cpp', 'ProbeAlpha.cpp', 'UnityProbeModule.cpp') }, dllChanged: true, followOn: ok },
  gitCommitted: { exit: 0, log: 'Target is up to date', unity: { 'Module.UnityProbe.cpp': unityText('PerModuleInline.gen.cpp', 'ProbeAlpha.cpp', 'UnityProbeModule.cpp') }, dllChanged: false, followOn: ok },
  gitRewritten: { exit: 6, log: clashLog, unity: { 'Module.UnityProbe.cpp': ALL }, dllChanged: false, followOn: skipped },
});

const failing = (phases) => evaluate(phases).filter((c) => !c.pass).map((c) => c.name);

test('the documented run passes every check', () => {
  const checks = evaluate(good());
  assert.deepEqual(failing(good()), []);
  assert.equal(summarize(checks).total, 11);
  assert.equal(summarize(checks).passed, 11);
});

test('log parsers read diagnostics, unity includes, compiled units and the adaptive exclusion', () => {
  const diags = compilerDiagnostics(clashLog);
  assert.deepEqual(diags.map((d) => d.code), ['C2374', 'C2086', 'C4459', 'C2872']);
  assert.ok(diags.every((d) => d.file === 'ProbeBeta.cpp' && d.kind === 'error'));
  assert.deepEqual(unityIncludes(ALL), ['PerModuleInline.gen.cpp', 'ProbeAlpha.cpp', 'ProbeBeta.cpp', 'UnityProbeModule.cpp']);
  assert.deepEqual(compiledUnits('[3/9] Compile [x64] ProbeAlpha.cpp\n[2/9] Compile Resource [x64] Default.rc2'), ['ProbeAlpha.cpp']);
  assert.deepEqual(adaptiveExcluded(excluded('A.cpp', 'B.cpp')), ['A.cpp', 'B.cpp']);
  assert.deepEqual(adaptiveExcluded('nothing'), []);
  assert.deepEqual(chunks({ a: ALL, b: GEN }), [['ProbeAlpha.cpp', 'ProbeBeta.cpp', 'UnityProbeModule.cpp']]);
});

test('a clash build that passes, or that misses a code, fails the reproduction check', () => {
  const passing = good(); passing.clash = { ...passing.clash, exit: 0 };
  assert.ok(failing(passing).includes('merged chunk reproduces the four errors'));
  const missing = good(); missing.clash.log = clashLog.replace(/C4459/g, 'C4458');
  assert.ok(failing(missing).includes('merged chunk reproduces the four errors'));
  const split = good(); split.clash.unity = { 'Module.UnityProbe.cpp': GEN };
  assert.ok(failing(split).includes('merged chunk reproduces the four errors'));
});

test('a failed build that changed the binary, or whose follow-on step ran, fails the stale-binary check', () => {
  const changed = good(); changed.clash.dllChanged = true;
  assert.ok(failing(changed).includes('failed build leaves the old binary and the guarded step is skipped'));
  const ran = good(); ran.clash.followOn = ok;
  assert.ok(failing(ran).includes('failed build leaves the old binary and the guarded step is skipped'));
  const skippedAfterSuccess = good(); skippedAfterSuccess.fixed.followOn = skipped;
  assert.ok(failing(skippedAfterSuccess).includes('failed build leaves the old binary and the guarded step is skipped'));
});

test('writable files that end up in the unity file fail the adaptive check', () => {
  const merged = good(); merged.adaptive.log = compileLines('Module.UnityProbe.cpp'); merged.adaptive.unity = { 'Module.UnityProbe.cpp': ALL };
  assert.ok(failing(merged).includes('writable files stay out of the unity file'));
});

test('a small module that builds as unity fails the threshold check', () => {
  const unity = good(); unity.small.unity = { 'Module.UnityProbe.cpp': ALL };
  assert.ok(failing(unity).includes('small module builds one file at a time'));
});

test('the unity-off, fixed-source and chunk-size phases each need their own facts', () => {
  const off = good(); off.off.exit = 6;
  assert.ok(failing(off).includes('unity off builds the same sources'));
  const offMerged = good(); offMerged.off.unity = { 'Module.UnityProbe.cpp': ALL };
  assert.ok(failing(offMerged).includes('unity off builds the same sources'));
  const fixed = good(); fixed.fixed.unity = { 'Module.UnityProbe.cpp': GEN };
  assert.ok(failing(fixed).includes('prefixed and qualified names pass in the merged chunk'));
  const chunksTogether = good(); chunksTogether.chunks.unity = { 'Module.UnityProbe.cpp': ALL };
  assert.ok(failing(chunksTogether).includes('smaller chunks regroup the files'));
});

test('the git phases need the edit excluded, the commit to be a no-op and the rewrite to fail again', () => {
  const clean = good(); clean.gitClean.exit = 0;
  assert.ok(failing(clean).includes('clean git tree builds the merged chunk'));
  const dirty = good(); dirty.gitDirty.log = excluded('ProbeAlpha.cpp');
  assert.ok(failing(dirty).includes('a modified file leaves the chunk and the build passes'));
  const noInvalidation = good(); noInvalidation.gitDirty.log = excluded('ProbeBeta.cpp');
  assert.ok(failing(noInvalidation).includes('a modified file leaves the chunk and the build passes'));
  const committed = good(); committed.gitCommitted.log = compileLines('ProbeBeta.cpp');
  assert.ok(failing(committed).includes('committing alone does not regroup'));
  const rewritten = good(); rewritten.gitRewritten = { ...rewritten.gitRewritten, exit: 0 };
  assert.ok(failing(rewritten).includes('a rewritten committed file regroups and fails again'));
});

test('a missing phase fails its checks instead of throwing', () => {
  const none = evaluate({});
  assert.equal(none.length, 11);
  assert.ok(none.every((c) => c.pass === false));
  assert.doesNotThrow(() => evaluate(undefined));
});

// ---- the opt-in read-only group (unity_build.mjs --readonly). The phases below are what reading SourceFileWorkingSet.cs and Unity.cs predicts, not a run: the shape is the
// shape of the phases above, the expected values are an assumption, and the first run on an engine confirms or refutes them.
const roGood = () => ({
  roAll: { exit: 6, log: clashLog, unity: { 'Module.UnityProbe.cpp': ALL }, dllChanged: false, followOn: skipped, extraArgs: [] },
  roBetaWritable: { exit: 0, log: excluded('ProbeBeta.cpp'), unity: { 'Module.UnityProbe.cpp': unityText('PerModuleInline.gen.cpp', 'ProbeAlpha.cpp', 'UnityProbeModule.cpp') }, dllChanged: true, followOn: ok, extraArgs: [] },
  roHeaderWritable: { exit: 0, log: excluded('ProbeAlpha.cpp', 'ProbeBeta.cpp'), unity: { 'Module.UnityProbe.cpp': unityText('PerModuleInline.gen.cpp', 'UnityProbeModule.cpp') }, dllChanged: true, followOn: ok, extraArgs: [] },
});
const roFailing = (phases) => evaluateReadOnly(phases).filter((c) => !c.pass).map((c) => c.name);
const RO_ALL = 'read-only files are not in the working set and share one unity file';
const RO_STALE = 'a failed read-only build leaves the old binary and skips the guarded step';
const RO_BETA = 'one writable source leaves the unity file and the build passes';
const RO_HEADER = 'a writable header takes the sources that include it first out of the unity file';

test('the read-only group passes on the phases the source predicts, and the default checks are untouched', () => {
  assert.deepEqual(roFailing(roGood()), []);
  assert.equal(evaluateReadOnly(roGood()).length, 4);
  assert.deepEqual(MODULE_FILES, ['ProbeAlpha.cpp', 'ProbeBeta.cpp', 'UnityProbeModule.cpp', 'UnityProbeTypes.h', 'UnityProbe.Build.cs']);
  assert.equal(evaluate({ ...good(), ...roGood() }).length, 11);
});

test('read-only sources that are excluded, built with -DisableAdaptiveUnity or not clashing fail the first check', () => {
  const excludedAll = roGood(); excludedAll.roAll.log = `${clashLog}
${excluded('ProbeAlpha.cpp')}`;
  assert.deepEqual(roFailing(excludedAll), [RO_ALL]);
  const passes = roGood(); passes.roAll = { ...passes.roAll, exit: 0, followOn: ok };
  assert.ok(roFailing(passes).includes(RO_ALL));
  const split = roGood(); split.roAll.unity = { 'Module.UnityProbe.cpp': GEN };
  assert.ok(roFailing(split).includes(RO_ALL));
  const flagged = roGood(); flagged.roAll.extraArgs = ['-DisableAdaptiveUnity'];
  assert.deepEqual(roFailing(flagged), [RO_ALL]);
});

test('a read-only clash that changed the binary or ran the follow-on step fails the stale-binary check', () => {
  const changed = roGood(); changed.roAll.dllChanged = true;
  assert.deepEqual(roFailing(changed), [RO_STALE]);
  const ran = roGood(); ran.roAll.followOn = ok;
  assert.deepEqual(roFailing(ran), [RO_STALE]);
});

test('the one-writable-source phase needs exactly ProbeBeta.cpp excluded and a pass', () => {
  const wrong = roGood(); wrong.roBetaWritable.log = excluded('ProbeAlpha.cpp');
  assert.deepEqual(roFailing(wrong), [RO_BETA]);
  const both = roGood(); both.roBetaWritable.log = excluded('ProbeAlpha.cpp', 'ProbeBeta.cpp');
  assert.deepEqual(roFailing(both), [RO_BETA]);
  const failed = roGood(); failed.roBetaWritable.exit = 6;
  assert.deepEqual(roFailing(failed), [RO_BETA]);
  const merged = roGood(); merged.roBetaWritable.unity = { 'Module.UnityProbe.cpp': ALL };
  assert.deepEqual(roFailing(merged), [RO_BETA]);
});

test('the writable-header phase needs both first-include sources excluded and the module file left in', () => {
  const onlyOne = roGood(); onlyOne.roHeaderWritable.log = excluded('ProbeBeta.cpp');
  assert.deepEqual(roFailing(onlyOne), [RO_HEADER]);
  const moduleToo = roGood(); moduleToo.roHeaderWritable.log = excluded('ProbeAlpha.cpp', 'ProbeBeta.cpp', 'UnityProbeModule.cpp');
  assert.deepEqual(roFailing(moduleToo), [RO_HEADER]);
  const failed = roGood(); failed.roHeaderWritable.exit = 6;
  assert.deepEqual(roFailing(failed), [RO_HEADER]);
});

test('a missing read-only phase fails its checks instead of throwing', () => {
  const none = evaluateReadOnly({});
  assert.equal(none.length, 4);
  assert.ok(none.every((c) => c.pass === false));
  assert.doesNotThrow(() => evaluateReadOnly(undefined));
});
